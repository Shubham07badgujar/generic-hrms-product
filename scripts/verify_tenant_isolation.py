#: Routes that raised instead of answering. An exception is not a refusal --
#: it is a bug -- so these are counted and reported separately rather than
#: quietly folded into either column.
ERRORED = []


def get(client, path):
    """
    A GET that returns a status instead of raising.

    The walk touches every detail route in the product. One view raising --
    a missing file on disk, a serializer that cannot render a half-built row --
    would otherwise abort the run and produce no report at all, which is the
    one outcome worse than a failing report.
    """
    try:
        return client.get(path).status_code
    except Exception as exc:  # noqa: BLE001 -- deliberately broad; see docstring
        ERRORED.append(f"{path} :: {type(exc).__name__}: {exc}")
        return None


def login(world, who):
    user = world[who]
    client = APIClient(HTTP_HOST="localhost")
    response = client.post(
        "/api/v1/auth/login/",
        {"email": user.email, "password": world["passwords"][user.email]},
        format="json",
    )
    if response.status_code != 200:
        return None
    client.credentials(HTTP_AUTHORIZATION="Bearer " + response.json()["access"])
    return client


