# Guards the guard. A run that performs no attempts reports no failures, and
# "0 failures" is exactly what a passing run looks like at a glance -- so a
# script that quietly did nothing would be indistinguishable from proof. This
# is not hypothetical: piping this file into `manage.py shell` does precisely
# that, because IPython treats a blank line inside a block as the end of it.
if len(RESULTS) < 50 or not WALK:
    raise SystemExit(
        f"verify_tenant_isolation: ONLY {len(RESULTS)} CHECKS RAN and "
        f"{len(WALK)} walks completed. The script did not execute properly -- "
        f"no report has been written. Invoke it with "
        f"`manage.py shell -c \"exec(open(...).read())\"`, not with `shell < file`."
    )

passed = [r for r in RESULTS if r[1] == "PASS"]
failed = [r for r in RESULTS if r[1] == "FAIL"]
skipped = [r for r in RESULTS if r[1] == "SKIP"]

total_served = sum(row[2] for row in WALK)
total_refused = sum(row[3] for row in WALK)
total_leaked = sum(len(row[4]) for row in WALK)

lines = []
w_ = lines.append

w_("# Tenant Isolation Test Report")
w_("")
w_(f"Generated {timezone.now():%Y-%m-%d %H:%M %Z} by "
   "`scripts/verify_tenant_isolation.py`.")
w_("")
w_("This file is written by the script that performs the attempts. It is not a "
   "description of a test run; it is the output of one. Re-running the script "
   "overwrites it.")
w_("")
w_("## Verdict")
w_("")
if failed:
    w_(f"**FAILED.** {len(failed)} of {len(RESULTS)} checks did not pass.")
else:
    w_(f"**PASSED.** {len(passed)} of {len(RESULTS)} checks passed"
       + (f", {len(skipped)} inconclusive." if skipped else ", none inconclusive."))
w_("")
w_("| | |")
w_("|---|---|")
w_(f"| Checks passed | {len(passed)} |")
w_(f"| Checks failed | {len(failed)} |")
w_(f"| Inconclusive (positive control did not succeed) | {len(skipped)} |")
w_(f"| Detail routes walked across organizations | {total_served} |")
w_(f"| Refused | {total_refused} |")
w_(f"| Served another organization's row | {total_leaked} |")
w_(f"| Raised instead of answering | {len(set(ERRORED))} |")
w_(f"| Detail routes exposed by the URL resolver, in total | {ROUTES_TOTAL} |")
w_(f"| ...of which answered for the caller's own row, and were therefore "
   f"asked about | {WALK[0][2] if WALK else 0} |")
w_("")

w_("## The organizations")
w_("")
w_("Fictional, generated per run. Every domain is `.example` (RFC 2606, "
   "unroutable). Passwords are generated in memory and are not written to this "
   "file, to any file, or to the source.")
w_("")
w_("| Organization | Slug | Employees | Departments | Locations |")
w_("|---|---|---|---|---|")
for w2 in WORLDS:
    w_(f"| {w2['name']} | `{w2['slug']}` | {len(w2['employees'])} | "
       f"{len(w2['departments'])} | {len(w2['locations'])} |")
w_("")

w_("## What was attempted")
w_("")
w_("Each organization's **Admin** made every attempt. Admin deliberately: they "
   "hold `Scope.ALL` on almost every resource, which is precisely the authority "
   "the organization predicate has to override. A principal with less authority "
   "proves less.")
w_("")
w_("Every cross-organization attempt is paired with the same request against the "
   "caller's **own** equivalent row. An attempt whose control did not return 200 "
   "is reported as inconclusive, never as a pass -- a route that refuses "
   "everybody would otherwise read as perfect isolation.")
w_("")
w_("| Attempt | Refusal required |")
w_("|---|---|")
w_("| List employees, departments, locations, leave, attendance, payroll runs, "
   "candidates, documents, audit logs | no other organization's row present |")
w_("| Read a named employee, department, location, leave request, attendance "
   "record, payroll run, candidate, document, leave type | 404 |")
w_("| Edit another organization's employee | 404 |")
w_("| Create an employee in another organization's department, with a payload "
   "valid in every other field | 400, naming the department |")
w_("| Open an exit, or file a resignation, for another organization's employee "
   "(a relation id in the body of a custom endpoint) | 400 or 404, and the "
   "employee unchanged |")
w_("| Every detail route the URL resolver exposes | 403, 404 or 405 |")
w_("| The same read as HR Head and as a plain employee | 403 or 404 |")
w_("")

w_("### Why 404 and not 403")
w_("")
w_("A 403 answers \"that record exists and you may not see it\", which tells one "
   "customer that a record of another customer's exists. The requirement is that "
   "another organization's row is indistinguishable from a row that was never "
   "there. Detail reads that answered 403 are listed below separately rather "
   "than counted as passes.")
w_("")
if DISCLOSED_BY_403:
    w_("**Answered 403 where 404 is required:**")
    w_("")
    for caller, victim, key in DISCLOSED_BY_403:
        w_(f"- {caller} -> {victim} / {key}")
else:
    w_("No detail read answered 403. Every refusal was a 404.")
w_("")

w_("## The full route walk")
w_("")
w_("The nine resources above are a list somebody chose. This walk is derived "
   "from the URL resolver instead, so a route added next year is covered the day "
   "it is added. Each route is filled with a **real id of the right model** "
   "belonging to another organization -- a random UUID would 404 for absence and "
   "prove nothing.")
w_("")
w_("| Caller | Target | Routes that answered for the caller's own row | Refused | Served |")
w_("|---|---|---|---|---|")
for caller, victim, served, refused, leaked in WALK:
    w_(f"| {caller} | {victim} | {served} | {refused} | {len(leaked)} |")
w_("")
if total_leaked:
    w_("**Routes that served another organization's row:**")
    w_("")
    for caller, victim, _s, _r, leaked in WALK:
        for entry in leaked:
            w_(f"- {caller} -> {victim}: `{entry}`")
    w_("")

w_("## Routes that raised instead of answering")
w_("")
w_("An exception is not a refusal. Nothing was served, so no data crossed a "
   "boundary, but a view that cannot render a row is a bug and is recorded "
   "here rather than folded into the refused column.")
w_("")
if ERRORED:
    for entry in sorted(set(ERRORED)):
        w_(f"- `{entry}`")
else:
    w_("None. Every route answered with a status code.")
w_("")

w_("## Every check")
w_("")
w_("| Result | Check | Detail |")
w_("|---|---|---|")
for name, status, detail in RESULTS:
    safe = detail.replace("|", "\\|").replace("\n", " ")[:160]
    w_(f"| {status} | {name} | {safe} |")
w_("")

w_("## What this does not prove")
w_("")
w_("Stated because a report that only lists what passed is not evidence, it is "
   "advertising.")
w_("")
w_("- **The organizations are built by this script, not by the platform "
   "provisioning service**, which does not exist yet. `provision()` is the seam: "
   "when that service lands, it replaces the body of that function and this "
   "report starts proving the real creation path too.")
w_(f"- **The walk reached {WALK[0][2] if WALK else 0} of the {ROUTES_TOTAL} "
   f"routes the resolver exposes.** A route is only asserted against when it "
   f"serves the CALLER's own row, because one that answers 405 or 404 for "
   f"everybody refuses both organizations equally and counting it as a "
   f"refusal would score the test against itself. The rest are dropped for "
   f"lack of an answer, not judged and passed. Most of the gap is "
   f"POST/PUT-only actions, file downloads with nothing uploaded, and the "
   f"`.json` suffix duplicates of routes already walked.")
w_("- **Celery tasks are not exercised here.** A task's isolation is a separate "
   "question with its own per-task tests, including the negative case where a "
   "task given another organization's object id must fail rather than silently "
   "do nothing.")
w_("- **Per-organization email, files and configuration are not covered.** Those "
   "arrive with the per-organization configuration work and get their own "
   "checks.")
w_("- **The platform layer is not covered**, because it does not exist yet. "
   "Whether a platform administrator is kept out of customer HR data is a "
   "question this report cannot yet answer.")
w_("")

report_path = Path(settings.BASE_DIR).parent.parent / "TENANT_ISOLATION_TEST_REPORT.md"
report_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

