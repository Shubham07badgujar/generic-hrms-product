"""
Prove tenant isolation against a running system, and write down what happened.

    cd apps/api
    python manage.py shell -c "exec(open('../../scripts/verify_tenant_isolation.py').read())"

Not `shell < script`. With IPython installed, Django's shell reads a redirected
file as if somebody were typing it, and a blank line inside an indented block
ends the block -- so the loops below silently do not run and the script reports
zero checks and zero failures, which is the most dangerous output it could
possibly produce. `exec()` compiles the whole file at once.

Three organizations are provisioned, populated with fictional HR data, and then
every one of them is told to go and fetch the others' records -- as its own
Admin, who holds Scope.ALL almost everywhere and is therefore the principal
with the most reach to override. Every attempt must be refused.

The output is `TENANT_ISOLATION_TEST_REPORT.md` at the repository root, written
from the results rather than from a description of them. That is the whole
point of the script: the brief asks not to be told the system is multi-tenant
but to be shown, and a document generated by the attempts themselves cannot
claim an attempt that was never made.

WHAT COUNTS AS A REFUSAL
------------------------
404, not 403. A 403 says "this exists and you may not have it", which tells
one customer that a record of another exists -- so the requirement is that
another organization's row is indistinguishable from a row that was never
there. The script records the distinction and reports 403s separately rather
than counting them as passes.

WHY EACH REFUSAL IS PAIRED WITH A POSITIVE CONTROL
--------------------------------------------------
A route that refuses everybody proves nothing about tenancy. Every cross-org
attempt below is preceded by the same request against the caller's OWN
equivalent row, and an attempt whose control did not succeed is reported as
INCONCLUSIVE rather than as a pass. Without that, a typo in a URL reads as
perfect isolation.

NO REAL DATA
------------
Every name, address and email here is invented, every domain is `.example`
(reserved by RFC 2606 and unroutable), and passwords are generated per run and
never written down -- not to a file, not to this source, not to the report.
"""

