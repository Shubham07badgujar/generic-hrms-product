def check(name, ok, detail="", *, inconclusive=False):
    status = "SKIP" if inconclusive else ("PASS" if ok else "FAIL")
    RESULTS.append((name, status, str(detail)[:300]))
    line = f"{status} {name}"
    if status != "PASS" and detail:
        line += f"  :: {str(detail)[:200]}"
    print(line)
    return ok


