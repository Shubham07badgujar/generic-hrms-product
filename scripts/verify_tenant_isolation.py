        for key, template in DETAIL_ROUTES.items():
            # The positive control, first and every time: the SAME route
            # against this caller's own row. A refusal below means nothing
            # unless this succeeded.
            control = get(client, template.format(w["rows"][key].pk))
            attempt = get(client, template.format(other["rows"][key].pk))
            STATUS_TALLY[attempt] += 1
            name = (f"5. {w['name']} reading {other['name']}'s {key}")
            if control != 200:
                check(name, False, f"control returned {control}", inconclusive=True)
                continue
            if attempt == 200:
                LEAKS.append((w["name"], other["name"], key, attempt))
                check(name, False, "SERVED IT (200)")
            elif attempt == 403:
                DISCLOSED_BY_403.append((w["name"], other["name"], key))
                check(name, False, "403 confirms the row exists; 404 required")
            else:
                check(name, attempt == 404, attempt)


