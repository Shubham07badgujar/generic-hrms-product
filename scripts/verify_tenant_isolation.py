def walk(caller, victim):
    """Every detail route the caller can answer, asked for the victim's row."""
    client = CLIENTS[(caller["slug"], "admin")]
    served, refused, leaked = 0, 0, []
    for template, view in detail_routes():
        if "pk" not in template:
            continue
        model = model_of(view)
        if model is None or not hasattr(model, "organization_id"):
            continue
        mine = rows_for(model, caller["organization"].pk).first()
        theirs = rows_for(model, victim["organization"].pk).first()
        if mine is None or theirs is None:
            continue
        my_path = concretize(template, mine.pk)
        their_path = concretize(template, theirs.pk)
        if not my_path or not their_path or my_path.startswith(EXCLUDED):
            continue
        # Only routes that answer for the caller's OWN row can distinguish a
        # tenancy refusal from a route that refuses everyone.
        if get(client, my_path) != 200:
            continue
        served += 1
        status = get(client, their_path)
        if status in (403, 404, 405):
            refused += 1
        elif status is None:
            pass  # raised rather than answered; counted in ERRORED, not here
        else:
            leaked.append(f"{status} {their_path} ({view.__name__} -> {model._meta.label})")
    return served, refused, leaked


